package tech.kayys.andalus.harness.journal;

/**
 * Standard event vocabulary representing state transitions in the durable journal.
 */
public enum ExecutionEventType {
    // Workflow graph and node events
    GRAPH_SUBMITTED,
    GRAPH_STARTED,
    NODE_READY,
    NODE_ADMITTED,
    NODE_STARTED,
    NODE_COMPLETED,
    NODE_FAILED,
    NODE_SKIPPED,
    CHECKPOINT_TAKEN,
    GRAPH_COMPLETED,
    GRAPH_FAILED,
    GRAPH_PAUSED,
    GRAPH_RESUMED,
    GRAPH_CANCELLED,

    // Execution lifecycle events
    EXECUTION_CREATED,
    EXECUTION_ADMITTED,
    EXECUTION_INITIALIZING,
    EXECUTION_STARTED,
    EXECUTION_WAITING,
    EXECUTION_SUSPENDED,
    EXECUTION_RESUMING,
    EXECUTION_RECOVERING,
    EXECUTION_COMPLETED,
    EXECUTION_FAILED,
    EXECUTION_CANCELLED,
    EXECUTION_EXPIRED,

    // Retry events
    EXECUTION_RETRY_SCHEDULED,
    EXECUTION_RETRY_STARTED,

    // Crash recovery events (6.13)
    RECOVERY_STARTED,
    RECOVERY_ACTION_DETECTED,
    RECOVERY_RECONCILE_REQUIRED,
    RECOVERY_RECONCILED,
    RECOVERY_RESUMED,
    RECOVERY_FAILED,

    // Compensation events (6.14)
    COMPENSATION_STARTED,
    COMPENSATION_ACTION_STARTED,
    COMPENSATION_ACTION_COMPLETED,
    COMPENSATION_ACTION_FAILED,
    COMPENSATION_COMPLETED,
    COMPENSATION_FAILED
}
